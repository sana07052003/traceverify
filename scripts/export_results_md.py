"""Write docs/RESULTS.md (tables + embedded figures) and copy the PNGs into docs/figures for the GitHub README.
Run after make_figures:   python -m scripts.export_results_md --out docs"""
import argparse
import json
import re
import shutil
from pathlib import Path

from traceverify import classical, config


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs")
    out = Path(ap.parse_args().out)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    R = {p.stem: json.loads(p.read_text()) for p in config.REPORT_DIR.glob("*.json")}
    src = config.ARTIFACT_DIR / "figures"
    pngs = sorted(src.glob("*.png")) if src.exists() else []
    for p in pngs:
        shutil.copy(p, out / "figures" / p.name)
    caps = {}
    if (src / "INDEX.md").exists():
        caps = dict(re.findall(r"- \*\*(.+?)\*\*: (.+)", (src / "INDEX.md").read_text()))

    L = ["# Results", "", "_Generated by `scripts/export_results_md.py` from `artifacts/reports/*.json`._", ""]
    dc = R.get("data_checks")
    if dc:
        L += ["## Data (official MOCHEG splits)", "", "| Split | Claims | With image | Without evidence |", "|---|---|---|---|"]
        for s in dc["claims"]:
            L.append(f"| {s} | {dc['claims'][s]} | {dc['claims_with_image'][s]} | {dc['claims_without_evidence'][s]} |")
        L += ["", f"Leakage check (no claim text/ID shared across splits): **{'passed' if dc.get('leakage_free') else 'FAILED'}**", ""]
    rows = []
    for n, r in R.get("classical", {}).items():
        rows.append((classical.NAMES.get(n, n), "Classical ML", r["test"], r.get("train_subset", "")))
    ens = R.get("ensemble", {})
    if ens.get("member_test", {}).get("deep_multimodal"):
        rows.append((classical.NAMES["deep_multimodal"], "Deep learning", ens["member_test"]["deep_multimodal"], ""))
    if ens.get("ensemble_test"):
        rows.append((classical.NAMES["stacking_ensemble"], "Ensemble", ens["ensemble_test"], ""))
    if rows:
        L += ["## Test-set performance (3-class, chance = 33.3%)", "", "| Algorithm | Family | Accuracy | Macro-F1 | Trained on |", "|---|---|---|---|---|"]
        for name, fam, m, sub in sorted(rows, key=lambda r: r[2]["macro_f1"], reverse=True):
            L.append(f"| {name} | {fam} | {pct(m['accuracy'])} | {m['macro_f1']:.3f} | {sub or '-'} |")
        L.append("")
    ret = R.get("retrieval")
    if ret:
        ks = sorted(ret["dense"], key=int)
        L += ["## Evidence retrieval (Recall@k)", "", "| Method | " + " | ".join(f"@{k}" for k in ks) + " |", "|---|" + "---|" * len(ks)]
        for key, nm in (("dense", "Dense (MiniLM + FAISS)"), ("hybrid", "Hybrid (dense + BM25)")):
            L.append(f"| {nm} | " + " | ".join(pct(ret[key][k]) for k in ks) + " |")
        L += ["", "_Recall@k = the claim's own annotated evidence appears in the top-k; it measures re-finding it._", ""]
    mod = R.get("deep", {}).get("modality")
    if mod:
        L += ["## Does the image help?", "", "| Setting | n | Accuracy | Macro-F1 |", "|---|---|---|---|"]
        for k, v in mod.items():
            if isinstance(v, dict) and "accuracy" in v:
                L.append(f"| {k.replace('_', ' ')} | {v['n']} | {pct(v['accuracy'])} | {v['macro_f1']:.3f} |")
        if "prediction_change_rate_image_subset" in mod:
            L += ["", f"The image changes the deep model's prediction for **{pct(mod['prediction_change_rate_image_subset'])}** of image claims.", ""]
    L += ["## Figures", ""]
    for p in pngs:
        L += [f"### {p.name}", "", f"![{p.name}](figures/{p.name})", "", caps.get(p.name, ""), ""]
    (out / "RESULTS.md").write_text("\n".join(L))
    print(f"wrote {out / 'RESULTS.md'} and {len(pngs)} figures")


if __name__ == "__main__":
    main()
